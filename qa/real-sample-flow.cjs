/* Actual HTTP backend + previously collected quotes. No generated bars or API mocks. */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright-core');
const url = process.env.REAL_FLOW_URL || 'http://127.0.0.1:18765';
const out = process.env.REAL_FLOW_OUTPUT || path.resolve('.qa-runtime', `real-e2e-${Date.now()}`);
const key = '000818|2025-12-17|left';

async function main() {
  fs.mkdirSync(out, { recursive: true });
  const catalogResponse = await fetch(`${url}/api/sample-candidates?view=summary`);
  const catalogText = await catalogResponse.text(), catalog = JSON.parse(catalogText);
  assert.equal(catalog.catalog.approvedPairsTotal, 10);
  assert.equal(catalog.catalog.trainableSamples, 20);
  assert.ok(Buffer.byteLength(catalogText) < 150000);
  const { candidate: sample } = await (await fetch(`${url}/api/sample-candidates?key=${encodeURIComponent(key)}`)).json();
  assert.ok(sample.trainable);
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--disable-gpu'] });
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, serviceWorkers: 'block' });
  const page = await context.newPage(), errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => requests.push(r.url()));
  page.on('dialog', d => d.accept());
  const draft = () => page.evaluate(() => JSON.parse(localStorage.getItem('kline-training-draft')));
  const ensureDetails = async selector => {
    const details = page.locator(selector);
    if (!(await details.getAttribute('open'))) {
      if (!(await details.evaluate(e => e.open))) await details.locator('summary').click();
    }
  };
  const note = async (tradeIndex, text, intent) => {
    const id = (await draft()).trades[tradeIndex].id;
    await page.locator(`#tradeLogBody [data-note-trade="${id}"]`).click();
    await page.locator('#barNoteModal').waitFor({ state: 'visible' });
    assert.ok(!(await page.locator('#barNoteMeta').innerText()).includes('000818'));
    await page.locator('#noteIntentInput').selectOption(intent);
    await page.locator('#noteCertaintyInput').selectOption('不确定');
    await page.locator('[data-note-signal="J值"]').check();
    await page.locator('[data-note-signal="量价"]').check();
    await page.locator('#barNoteInput').fill(text);
    await page.locator('#saveBarNoteButton').click();
    await page.locator('#closeBarNoteButton').click();
  };
  const buy = async (divisor, role, intent, reason) => {
    await ensureDetails('.tranche-plan-fields');
    await page.locator('#trancheRoleInput').selectOption(role);
    await page.locator('#tranchePurposeInput').fill('真实行情功能验收：批次用途，不代表推荐操作');
    await page.locator('#trancheExitInput').fill('先记录失效条件，不因事后结果覆盖');
    await ensureDetails('#tradeDecisionCapture');
    await page.locator('#tradeIntentInput').selectOption(intent);
    await page.locator('#tradeCertaintyInput').selectOption('不确定');
    await page.locator('[data-trade-signal="J值"]').check();
    await page.locator('[data-trade-signal="量价"]').check();
    await page.locator('#tradeReasonInput').fill(reason);
    await page.locator(`[data-quick-side="buy"][data-divisor="${divisor}"]`).click();
    const qty = Number(await page.locator('#quantityInput').inputValue());
    assert.ok(qty >= 100 && qty % 100 === 0);
    await page.locator('#buyButton').click();
    return { qty, data: await draft() };
  };
  try {
    await page.goto(url, { waitUntil: 'networkidle' });
    await page.waitForFunction(() => state.serverCatalogLoaded);
    assert.match(await page.locator('#sampleLibraryStatus').innerText(), /20/);
    assert.ok(!requests.some(r => new URL(r).pathname === '/api/sample-candidates' && !new URL(r).search));
    await page.locator(`[data-side-action="train"][data-candidate-key="${key}"]`).click();
    await page.waitForFunction(() => state.bars.length === 220 && !state.sampleLoadingKey);
    const loaded = await draft();
    assert.equal(loaded.code, '000818');
    assert.equal(loaded.indicatorWarmupBars.length, 250);
    assert.equal(Object.keys(loaded.intradayData).length, 220);
    assert.deepEqual(loaded.bars.map(b => b.close), sample.bars.map(b => b.close));
    assert.deepEqual(loaded.intradayData, sample.intradayByDate);
    const canvas = page.locator('#chartCanvas'); await canvas.scrollIntoViewIfNeeded();
    await page.locator('#chartNoteTool').click();
    const canvasBox = await canvas.boundingBox();
    const noteX = canvasBox.width - 14 - Math.min(132, Math.max(88, canvasBox.width * .17)) - 10;
    await page.mouse.click(canvasBox.x + noteX, canvasBox.y + 120);
    await page.locator('#barNoteModal').waitFor({ state: 'visible' });
    await page.locator('#noteIntentInput').selectOption('空仓等待');
    await page.locator('#noteCertaintyInput').selectOption('不确定');
    await page.locator('[data-note-signal="J值"]').check();
    await page.locator('#barNoteInput').fill('J<10时观察量价，先记录再决定。');
    await page.locator('#noteKeyLevelInput').fill(String(loaded.bars[loaded.currentIndex].low));
    await page.locator('#confirmParsedNote').check();
    await page.locator('#saveBarNoteButton').click();
    await page.locator('#closeBarNoteButton').click();
    const originalNote = (await draft()).barNotes.at(-1);
    assert.equal(originalNote.kind, 'original'); assert.equal(originalNote.index, loaded.currentIndex);
    assert.ok(originalNote.parsedCandidates.every(c => c.status === '用户确认'));
    await page.locator('#chartMarkLabel').fill('支撑观察');
    await page.locator('#chartMarkReason').fill('功能验收标记');
    await page.locator('[data-chart-tool="support"]').click();
    const markCanvas = await canvas.boundingBox();
    await page.mouse.click(markCanvas.x + markCanvas.width * .4, markCanvas.y + 140);
    await page.mouse.click(markCanvas.x + markCanvas.width * .65, markCanvas.y + 140);
    await page.waitForFunction(() => state.chartMarks.length === 1);
    assert.equal((await draft()).chartMarks[0].label, '支撑观察');
    const observed = await page.evaluate(() => operationIndicatorSnapshot(state.currentIndex));
    const first = await buy(6, '试探', '试探买入', `功能验收：当时J=${observed.j}，小仓观察，量价判断不确定`);
    const firstLot = first.data.trades.at(-1).lotId;
    await page.locator('#sellLotSelect').selectOption(firstLot);
    await page.locator('[data-quick-side="sell"][data-divisor="1"]').click();
    await ensureDetails('#tradeDecisionCapture');
    await page.locator('#tradeIntentInput').selectOption('全部退出');
    assert.match(await page.locator('#tradeHint').innerText(), /没有可卖|T\+1/);
    assert.equal((await draft()).trades.length, 1);
    await note(0, '试探买入时量价判断不确定；这是当时记录，不认为J低就一定见底。', '试探买入');
    await page.locator('#nextButton').click();
    const second = await buy(3, '确认加仓', '预定分批买入', '功能验收：按事先安排新增1/3，未确认量价转强。');
    const secondLot = second.data.trades.at(-1).lotId;
    // Another real same-day trade proves notes are not spread across all fills on that bar.
    await page.locator('#quantityInput').fill('100');
    await page.locator('#tradeReasonInput').fill('同根另一笔100股，独立理由');
    await page.locator('#buyButton').click();
    await note(1, '本笔预定分批买入，不要套用到同根另一次100股成交。', '预定分批买入');
    let saved = await draft();
    const noteBefore = structuredClone(saved.barNotes);
    const tradeNotesBefore = structuredClone(saved.reviewNotes);
    assert.equal(tradeNotesBefore.length, 2);
    assert.equal(tradeNotesBefore[1].targetId, saved.trades[1].id);
    assert.ok(!tradeNotesBefore.some(n => n.targetId === saved.trades[2].id));
    await page.reload({ waitUntil: 'networkidle' });
    saved = await draft();
    assert.equal(saved.trades.length, 3);
    assert.deepEqual(saved.barNotes, noteBefore);
    assert.deepEqual(saved.reviewNotes, tradeNotesBefore);
    assert.deepEqual(saved.intradayData, sample.intradayByDate);
    await page.locator('#nextButton').click();
    await page.locator('#sellLotSelect').selectOption(firstLot);
    await page.locator('[data-quick-side="sell"][data-divisor="1"]').click();
    await ensureDetails('#tradeDecisionCapture');
    await page.locator('#tradeIntentInput').selectOption('全部退出');
    await page.locator('#tradeReasonInput').fill('试探仓退出；不推断后续走势');
    await page.locator('#sellButton').click();
    let firstSale = (await draft()).trades.at(-1);
    assert.equal(firstSale.side, 'sell'); assert.equal(firstSale.qty, first.qty);
    assert.equal(firstSale.allocations[0].lotId, firstLot);
    await page.locator('#nextButton').click();
    await page.locator('#sellLotSelect').selectOption(secondLot);
    await page.locator('[data-quick-side="sell"][data-divisor="2"]').click();
    await page.locator('#tradeIntentInput').selectOption('分批减仓');
    const half = Number(await page.locator('#quantityInput').inputValue());
    assert.equal(half, Math.floor(second.qty / 2 / 100) * 100);
    await page.locator('#tradeReasonInput').fill('确认仓减半，保留剩余仓观察');
    await page.locator('#sellButton').click();
    saved = await draft();
    assert.equal(saved.trades.length, 5);
    assert.equal(saved.lots.find(l => l.id === secondLot).qty, second.qty - half);
    assert.ok(!saved.lots.some(l => l.id === firstLot && l.qty > 0));
    const cash = saved.trades.reduce((v, t) => v + (t.side === 'buy' ? -t.qty * t.price : t.qty * t.price) - t.fee, 1000000);
    assert.ok(Math.abs(cash - saved.cash) < 0.02);
    await page.screenshot({ path: path.join(out, 'real-training-1366-full-page.png'), fullPage: true });
    const chart = page.locator('#chartCanvas'); await chart.scrollIntoViewIfNeeded();
    const box = await chart.boundingBox();
    const x = box.width - 14 - Math.min(132, Math.max(88, box.width * .17)) - 10;
    await page.locator('#chartInspectTool').click();
    const intradayBox = await chart.boundingBox();
    await page.mouse.dblclick(intradayBox.x + x, intradayBox.y + 120);
    await page.locator('#intradayVolumeModal').waitFor({ state: 'visible' });
    await page.waitForFunction(() => state.intraday.bars?.length === 48);
    const intraday = await page.evaluate(() => ({ bars: state.intraday.bars, index: state.intraday.index }));
    const intradayText = await page.locator('#intradayVolumeStatus').innerText();
    assert.ok(intraday.bars.every(b => Number.isFinite(b.close) && Number.isFinite(b.volume)));
    await page.screenshot({ path: path.join(out, 'real-intraday-1366-full-page.png'), fullPage: true });
    await page.locator('#closeIntradayVolumeAction').click();
    const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#exportSessionButton').click()]);
    const backupPath = path.join(out, 'real-training-backup.json'); await download.saveAs(backupPath);
    const backup = JSON.parse(fs.readFileSync(backupPath)); assert.deepEqual(backup.intradayData, sample.intradayByDate); assert.equal(backup.chartMarks.length, 1); assert.equal(backup.chartMarkActions.length, 1);
    await page.locator('#finishButton').click();
    await page.waitForFunction(() => state.finished && state.reviewId);
    const id = await page.evaluate(() => state.reviewId);
    await page.waitForFunction(async id => {
      const r = await fetch(`/api/reviews/${id}`); const data=await r.json(); return r.ok && data.trades?.length === 5 && data.chartMarks?.length === 1;
    }, id);
    await page.locator('#openMyReviewsButton').click();
    await page.locator(`[data-open-review="${id}"]`).click();
    await page.locator('#reviewWorkspace').waitFor({ state: 'visible' });
    assert.ok(await page.locator('#reviewArchiveList').isHidden());
    const review = await (await fetch(`${url}/api/reviews/${id}`)).json();
    const causal = await page.evaluate(() => {
      const trade = state.trades[0], full = state.bars;
      const before = operationTradeEvidence(trade).evidence;
      try { state.bars = full.slice(0, trade.index + 1); return { before, after: operationTradeEvidence(trade).evidence }; }
      finally { state.bars = full; }
    });
    assert.deepEqual(causal.before, causal.after);
    assert.equal(await page.locator('#reviewRuleCardCatalog .review-rule-item').count(), 40);
    assert.equal(review.trades.length, 5); assert.deepEqual(review.barNotes, saved.barNotes);
    assert.deepEqual(review.chartMarks, backup.chartMarks); assert.equal(review.chartMarkActions.length, 1);
    assert.deepEqual(review.reviewNotes, saved.reviewNotes);
    assert.deepEqual(review.intradayData, sample.intradayByDate);
    assert.equal(review.trades.at(-1).allocations[0].lotId, secondLot);
    assert.ok((await page.locator('#operationWaves').innerText()).length > 0);
    await page.locator('[data-focus-wave="0"]').click();
    assert.equal(await page.evaluate(() => state.focusedWaveId), await page.evaluate(() => operationReviewData()[0].id));
    await page.locator('#allWavesButton').click();
    const ledger = await page.evaluate(() => ({ stats: sessionStats(), fees: operationReviewData().reduce((v,w) => v + w.fees,0), net: operationReviewData().reduce((v,w) => v + w.netChange,0) }));
    assert.ok(Math.abs(ledger.fees - saved.trades.reduce((v,t) => v + t.fee,0)) < .02);
    assert.ok(Math.abs(ledger.net - ledger.stats.returnRate * 10000) < .05);
    const checkItem = page.locator('[data-next-suggestion]').first();
    assert.ok(await checkItem.count()); await checkItem.check();
    await page.evaluate(() => reviewArchiveSaveQueue);
    assert.ok(await page.locator('[data-review-answer-option]').count() > 0);
    await page.locator('[data-review-answer-option]').first().click();
    await page.locator('#reviewQuestionText').fill('事后复盘：量价仍不明确，下次先记失效条件，不能冒充原计划。');
    await page.locator('#reviewQuestionSave').click();
    await page.locator('#reviewConclusionInput').fill('真实行情功能验收结论：批次操作及笔记完整；学习重点是区分预定分批与新确认，并事先写清退出条件。');
    await page.locator('#saveReviewConclusionButton').click();
    await page.evaluate(() => reviewArchiveSaveQueue);
    await page.waitForFunction(async id => (await (await fetch(`/api/reviews/${id}`)).json()).reviewConclusions?.length > 0, id);
    const options = await page.locator('#comparisonTradeSelect option').evaluateAll(opts => opts.map(o => o.value).filter(Boolean));
    assert.ok(options.length > 0);
    await page.locator('#comparisonTradeSelect').selectOption(options[0]);
    await page.locator('#comparisonTriggerPrice').fill(String(firstSale.price));
    await page.locator('#runTeachingComparison').click();
    await page.evaluate(() => reviewArchiveSaveQueue);
    assert.match(await page.locator('#teachingComparisonResults').innerText(), /教学对照|后续数据/);
    await page.screenshot({ path: path.join(out, 'real-review-1366-full-page.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 1366);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForTimeout(200);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
    await page.screenshot({ path: path.join(out, 'real-review-390-full-page.png'), fullPage: true });
    await page.screenshot({ path: path.join(out, 'real-review-390-viewport.png') });
    const [reviewDownload] = await Promise.all([page.waitForEvent('download'), page.locator('#exportCurrentReviewButton').click()]);
    await reviewDownload.saveAs(path.join(out, 'real-review-example.json'));
    await page.locator('#closeReviewWorkspaceButton').click();
    assert.ok((await draft()).reviewQuestionnaire.answers.length > 0);
    await page.reload({ waitUntil: 'networkidle' });
    assert.ok((await draft()).reviewQuestionnaire.answers.length > 0);
    assert.ok((await (await fetch(`${url}/api/reviews/${id}`)).json()).reviewQuestionnaire.answers.length > 0);
    await page.setViewportSize({ width: 1366, height: 900 });
    await page.locator('#resetButton').click();
    const active = await draft();
    await page.locator(`[data-open-review="${id}"]`).click();
    await page.locator('#reviewWorkspace').waitFor({ state: 'visible' });
    await page.locator('#closeReviewWorkspaceButton').click();
    const returned = await draft();
    assert.equal(returned.currentIndex, active.currentIndex); assert.deepEqual(returned.trades, active.trades);
    const fresh = await browser.newContext({ serviceWorkers: 'block' });
    const importPage = await fresh.newPage(); importPage.on('dialog', d => d.accept());
    await importPage.goto(url, { waitUntil: 'networkidle' });
    await importPage.locator('#backupFileInput').setInputFiles(backupPath);
    await importPage.waitForFunction(() => state.trades.length === 5);
    const beforeImportCount = (await (await fetch(`${url}/api/reviews`)).json()).reviews.length;
    const importedResponse = importPage.waitForResponse(r => r.url().endsWith('/api/reviews/import') && r.request().method() === 'POST');
    await importPage.locator('#reviewArchiveFileInput').setInputFiles(path.join(out, 'real-review-example.json'));
    const restoredReviewResponse = await importedResponse;
    assert.ok(restoredReviewResponse.ok()); assert.equal((await restoredReviewResponse.json()).imported, 1);
    assert.equal((await (await fetch(`${url}/api/reviews`)).json()).reviews.length, beforeImportCount);
    const restored = await importPage.evaluate(() => ({ intradayData: state.intradayData, notes: state.barNotes, code: state.code }));
    assert.deepEqual(restored.intradayData, sample.intradayByDate); assert.deepEqual(restored.notes, saved.barNotes);
    assert.equal(restored.code, '000818'); await fresh.close();
    const finalArchive = await (await fetch(`${url}/api/reviews/${id}`)).json();
    assert.ok(finalArchive.reviewQuestionnaire.answers.length > 0);
    assert.ok(finalArchive.reviewConclusions.length > 0);
    assert.ok(finalArchive.nextSessionChecklist.length > 0);
    assert.deepEqual(finalArchive.trades, review.trades);
    const legacyId = '12e67d01-8cf8-4fa1-bd20-90d6757c087a';
    const legacyBefore = await (await fetch(`${url}/api/reviews/${legacyId}`)).json();
    await page.locator(`[data-open-review="${legacyId}"]`).click();
    await page.locator('#reviewWorkspace').waitFor({ state: 'visible' });
    const legacyView = await page.evaluate(() => ({code: state.code, trades: state.trades.length, notes: state.barNotes.length + state.reviewNotes.length, intradayDays: Object.keys(state.intradayData).length, waves: operationReviewData().length, questions: buildReviewQuestions().length}));
    assert.equal(legacyView.code, '000818'); assert.equal(legacyView.trades, 17);
    assert.equal(legacyView.notes, legacyBefore.barNotes.length + legacyBefore.reviewNotes.length);
    assert.equal(legacyView.intradayDays, 220); assert.ok(legacyView.waves > 0 && legacyView.questions > 0);
    assert.deepEqual(await (await fetch(`${url}/api/reviews/${legacyId}`)).json(), legacyBefore);
    await page.locator('#closeReviewWorkspaceButton').click();
    assert.deepEqual(errors, []);
    const result = { realQuotesOnly: true, generatedBars: 0, mockedAPIs: 0, sample: key, catalog: catalog.catalog,
      summaryBytes: Buffer.byteLength(catalogText), visibleBars: 220, warmupBars: 250, intradayDays: 220,
      firstQty: first.qty, secondQty: second.qty, secondSold: half, cash: saved.cash,
      trades: saved.trades.length, originalNotes: saved.barNotes.length, tradePostscripts: saved.reviewNotes.length,
      sameDayTradeNotesIsolated: true, fees: saved.trades.reduce((v,t) => v + t.fee,0),
      reviewId: id, questionsAnswered: finalArchive.reviewQuestionnaire.answers.length,
      checklistItems: finalArchive.nextSessionChecklist.length, ledgerAndWaveFocusChecked: true, reviewImportDeduplicated: true,
      legacyActualReview: legacyView, decisionEvidenceTruncationMatched: true,
      teachingComparisons: finalArchive.teachingComparisons.length, intradayStatus: intradayText,
      refreshAndBackupRestored: true, independentWorkspace: true, pageErrors: errors, screenshots: out };
    fs.writeFileSync(path.join(out, 'real-flow-result.json'), JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result, null, 2));
  } catch (e) {
    await page.screenshot({ path: path.join(out, 'failure.png'), fullPage: true }).catch(() => {});
    console.error('page', await page.evaluate(() => ({hint: document.querySelector('#tradeHint')?.innerText, errors: document.querySelector('#reviewArchiveStatus')?.innerText})).catch(() => ({})));
    throw e;
  } finally { await context.close(); await browser.close(); }
}
main().catch(e => { console.error(e); process.exitCode = 1; });
